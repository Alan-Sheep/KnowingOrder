const spaces = new Map(domains.map(domain => [domain.name, []]));
const departments = domains.map(domain => domain.unit);
let serial = 0;
for (let index = 0; index < total; index++) {
  const domain = domains[index % domains.length];
  const list = domain.topics;
  const topicPair = list[Math.floor(index / domains.length) % list.length];
  const year = years[(index * 5 + Math.floor(index / domains.length)) % years.length];
  const term = terms[Math.floor(index / (domains.length * 2)) % terms.length];
  const campus = campuses[Math.floor(index / (domains.length * terms.length)) % campuses.length];
  const audience = domain.audiences[Math.floor(index / (domains.length * terms.length * campuses.length)) % domain.audiences.length];
  const type = domain.types[Math.floor(index / (domains.length * terms.length * campuses.length * domain.audiences.length)) % domain.types.length];
  const rule = ruleOf(topicPair[0]);
  const perSpace = spaces.get(domain.name).length + 1;
  const title = `${year}年${term}${campus}${audience}${topicPair[0]}${type}（第${String(perSpace).padStart(3, '0')}号）`;
  assert.ok(title.length <= 128, '生成的标题超过 128 字');
  spaces.get(domain.name).push({ title, sections: sectionsOf(domain, topicPair, rule, year, term, campus, audience, type, ++serial) });
}

